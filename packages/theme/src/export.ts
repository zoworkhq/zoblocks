export interface ImportReport {
  /** Palette steps understood. */
  matched: Record<string, Record<string, string>>;
  /** Keys present in the file that mean nothing here, with their paths. */
  unmatched: string[];
  /**
   * Clinical tokens found and discarded.
   *
   * Reported rather than silently dropped: a customer whose file contained a
   * status colour needs to know it did not take effect, and needs to know
   * *before* they confirm — otherwise the first they hear of it is a support
   * conversation about a red that did not change.
   */
  discardedClinical: string[];
}

const CLINICAL_PATH = /^(status|flag)\./;

/**
 * Read a DTCG document into a palette.
 *
 * Deliberately conservative. Only `ref.*` colour steps are taken, because that
 * is the whole surface a theme is allowed to set; everything else is reported
 * as unmatched rather than guessed at. An import that quietly ignores half a
 * file is how a customer concludes the import worked.
 */
export function importDtcg(document: unknown): ImportReport {
  const matched: Record<string, Record<string, string>> = {};
  const unmatched: string[] = [];
  const discardedClinical: string[] = [];

  const walk = (node: unknown, path: string[]): void => {
    if (!node || typeof node !== "object") return;
    const record = node as Record<string, unknown>;

    if ("$value" in record) {
      const dotted = path.join(".");

      if (CLINICAL_PATH.test(dotted)) {
        discardedClinical.push(dotted);
        return;
      }

      const [head, group, step] = path;
      if (head === "ref" && group && step && typeof record.$value === "string") {
        (matched[group] ??= {})[step] = record.$value;
        return;
      }
      unmatched.push(dotted);
      return;
    }

    for (const [key, child] of Object.entries(record)) {
      if (key.startsWith("$")) continue;
      walk(child, [...path, key]);
    }
  };

  walk(document, []);
  return { matched, unmatched, discardedClinical };
}

/**
 * Read an antd or MUI theme object into a palette.
 *
 * Lossy in one direction and the UI must say so: neither framework has a
 * concept of clinical status, so those tokens keep Oxygen's validated values
 * rather than arriving from the file.
 */
export function importFrameworkTheme(theme: unknown): ImportReport {
  const matched: Record<string, Record<string, string>> = {};
  const unmatched: string[] = [];
  const record = (theme ?? {}) as Record<string, unknown>;

  const antd = record.token as Record<string, unknown> | undefined;
  const mui = (record.palette as Record<string, unknown> | undefined)?.primary as
    Record<string, unknown> | undefined;

  const brand: Record<string, string> = {};
  const take = (value: unknown, step: string) => {
    if (typeof value === "string") brand[step] = value;
  };

  take(antd?.colorPrimary ?? mui?.main, "600");
  take(antd?.colorPrimaryHover ?? mui?.dark, "700");
  take(antd?.colorPrimaryBg, "50");
  take(mui?.light, "400");

  if (Object.keys(brand).length) matched.brand = brand;

  for (const key of Object.keys(antd ?? {})) {
    if (
      !["colorPrimary", "colorPrimaryHover", "colorPrimaryBg", "colorPrimaryBorder"].includes(key)
    ) {
      unmatched.push(`token.${key}`);
    }
  }

  return {
    matched,
    unmatched,
    // Always. Neither framework can express the direction of an abnormal
    // result, so there is nothing here that could have carried it.
    discardedClinical: ["status.*", "flag.*"],
  };
}
