/**
 * A signature, drawn by the real engine — ahead of time.
 *
 * The catalog's rule is that a card shows the actual component. Signature
 * cannot follow that literally: it wraps Ant Design, and the docs site does not
 * carry antd. Pulling a component framework into the marketing bundle to fill a
 * 92-pixel cell is the wrong trade.
 *
 * So the geometry below is not hand-drawn — it is the output of
 * `toInkPaths()` from `@oxygenui-design/signature-core`, the exact function the
 * live pad calls on every pointer move, run over the stroke model in
 * `SIGNATURE_STROKES`. Smoothing, decimation and the velocity-driven width
 * curve are all the component's own.
 *
 * The model itself is authored rather than captured, and authored the way a
 * hand actually writes: the letterforms are cubic Béziers, sampled at a fixed
 * arc-length step, with each sample's timestamp set from the two-thirds power
 * law — pen speed rising with the cube root of the radius of curvature. That
 * one rule is what makes the tight turns heavy and the open sweeps light,
 * because the engine derives stroke width from speed. Timing invented without
 * it produces uniform ink, and the signature reads as wire rather than
 * handwriting.
 *
 * It is baked rather than computed at render time because the model is
 * constant: recomputing it per request is waste, and a fixed result keeps the
 * catalog card and the page's replay animation in step.
 *
 * `packages/signature-core/test/docs-mark.test.ts` re-runs the engine over
 * `SIGNATURE_STROKES` and fails if this file has drifted, so "the engine's
 * output" stays a fact rather than a claim. That test also prints the
 * refreshed data when it fails.
 */

